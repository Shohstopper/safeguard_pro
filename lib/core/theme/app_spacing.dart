/// Spacing values (padding and gaps) from the Figma design, in pixels.
///
/// The number in each name is the size, so `space16` is 16 pixels.
abstract final class AppSpacing {
  static const double space2 = 2;
  static const double space4 = 4;
  static const double space8 = 8;
  static const double space10 = 10;
  static const double space12 = 12;
  static const double space13 = 13;
  static const double space14 = 14;
  static const double space16 = 16;
  static const double space20 = 20;
  static const double space24 = 24;
}

/// Corner radius values from the Figma design.
abstract final class AppRadius {
  static const double sectionMarker = 2;
  static const double badge = 12;
  static const double input = 14;
  static const double button = 14;
  static const double card = 20;
}

/// Fixed sizes of small design elements (icons, logo, borders).
abstract final class AppSizes {
  static const double borderThin = 1;
  static const double borderInput = 1.5;
  static const double sectionMarkerWidth = 3;
  static const double sectionMarkerHeight = 14;
  static const double iconSmall = 14;
  static const double iconMedium = 16;
  static const double iconLarge = 18;
  static const double spinner = 18;
  static const double spinnerStroke = 2.5;
  static const double loginLogoBoxWidth = 250;
  static const double loginLogoBoxHeight = 72;
  static const double loginLogoHeight = 56;
  static const double inputIconAreaWide = 46;
  static const double inputIconAreaNarrow = 36;
}
